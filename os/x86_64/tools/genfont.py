#!/usr/bin/env python3
"""Rasterise TTF fonts into C alpha-bitmap tables (ASCII 32..126) for the VelaOS kernel."""
import sys
from PIL import Image, ImageDraw, ImageFont

FONTS = [
    # (c name, ttf path, pixel size, fixed cell width or None for proportional)
    ("font_mono", "/usr/share/fonts/truetype/jetbrains-mono/JetBrainsMono-Regular.ttf", 15, 9),
    ("font_ui",   "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", 14, None),
    ("font_bold", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 14, None),
    ("font_big",  "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 34, None),
]

out = ["/* Generated by tools/genfont.py - do not edit. */", '#include "font.h"', ""]
for name, path, size, cellw in FONTS:
    f = ImageFont.truetype(path, size)
    asc, desc = f.getmetrics()
    h = asc + desc + 2
    advs = []
    for c in range(32, 127):
        advs.append(int(round(f.getlength(chr(c)))) if cellw is None else cellw)
    w = max(advs) + 2
    data = []
    for i, c in enumerate(range(32, 127)):
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((0, 1), chr(c), font=f, fill=255)
        data.extend(img.tobytes())
    out.append(f"static const unsigned char {name}_px[] = {{")
    for i in range(0, len(data), 32):
        out.append("  " + ",".join(str(b) for b in data[i:i+32]) + ",")
    out.append("};")
    out.append(f"static const unsigned char {name}_adv[] = {{{','.join(map(str, advs))}}};")
    out.append(f"const font_t {name} = {{ {w}, {h}, {name}_adv, {name}_px }};")
    out.append("")
open(sys.argv[1], "w").write("\n".join(out))
