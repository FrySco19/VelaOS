  await page.waitForFunction(()=>!document.getElementById('approve').disabled);
  await page.evaluate(()=>Promise.all(document.getAnimations().filter(a=>Number.isFinite(a.effect.getTiming().iterations)).map(a=>a.finished.catch(()=>{}))));
  await page.screenshot({path:path.join(output,'redesign-security.png')});
  await page.mouse.click(8,8);
  if(!await page.locator('#approval').isVisible())throw new Error('Backdrop dismissed approval');
  await page.locator('#reject').focus();await page.keyboard.press('Enter');
  await page.waitForFunction(()=>!document.getElementById('approval').open);
  if(frames!==0)throw new Error('Default Enter signed');
  await page.fill('#intent','Appunta un progetto di bridge');await page.press('#intent','Enter');
  await page.waitForSelector('#approval:visible');
  await page.keyboard.press('Tab');
  await page.waitForFunction(()=>!document.getElementById('approve').disabled);
  await page.locator('#approve').focus();await page.keyboard.press('Tab');
  if(await page.evaluate(()=>document.activeElement.id)!=='draft')throw new Error('Focus escaped the dialog');
  await page.locator('#draft').focus();await page.keyboard.press('Shift+Tab');
  if(await page.evaluate(()=>document.activeElement.id)!=='approve')throw new Error('Reverse focus trap failed');
  await page.fill('#draft','é'.repeat(600));
  await page.waitForFunction(()=>document.getElementById('planDigest').childElementCount===0);
  if(!await page.isDisabled('#approve'))throw new Error('Oversize payload can be approved');
  await page.fill('#draft','Payload esatto <script> — nessuna interpretazione HTML.');
  const expected=crypto.createHash('sha256').update(await page.inputValue('#draft')).digest('hex');
  await page.waitForFunction(hash=>document.getElementById('planDigest').textContent===hash,expected);
  await page.evaluate(()=>Promise.all(document.getAnimations().filter(a=>Number.isFinite(a.effect.getTiming().iterations)).map(a=>a.finished.catch(()=>{}))));
