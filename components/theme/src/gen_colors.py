#!/usr/bin/env python3
"""Generate the KDE color schemes VelaChiaro / VelaScuro from tokens.json."""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
T = json.load(open(os.path.join(HERE, '..', 'tokens.json')))
OUT = os.path.join(HERE, '..', 'overlay', 'usr', 'share', 'color-schemes')

def rgb(h):
    h = h.lstrip('#'); return ','.join(str(int(h[i:i+2], 16)) for i in (0, 2, 4))

def mix(a, b, t):
    a = a.lstrip('#'); b = b.lstrip('#')
    ca = [int(a[i:i+2], 16) for i in (0, 2, 4)]; cb = [int(b[i:i+2], 16) for i in (0, 2, 4)]
    return '#' + ''.join('%02X' % round(x + (y - x) * t) for x, y in zip(ca, cb))

def group(bg, alt, fg, inactive, c, focus):
    return {
        'BackgroundNormal': bg, 'BackgroundAlternate': alt,
        'DecorationFocus': focus, 'DecorationHover': focus,
        'ForegroundNormal': fg, 'ForegroundInactive': inactive,
        'ForegroundActive': c['accent'], 'ForegroundLink': c['link'],
        'ForegroundVisited': '#8A5BA8' if bg.upper() > '#888888' else '#B58CD0',
        'ForegroundNegative': c['negative'], 'ForegroundNeutral': c['neutral'],
        'ForegroundPositive': c['positive'],
    }

def scheme(kind, override=None, name=None, label=None):
    c = dict(T[kind]); dark = kind == 'dark'
    if override: c.update(override)
    focus = c['accent']
    g = {}
    g['Window'] = group(c['window'], mix(c['window'], c['text'], 0.06), c['text'], c['textSecondary'], c, focus)
    g['View'] = group(c['view'], c['viewAlt'], c['text'], c['textSecondary'], c, focus)
    g['Button'] = group(c['button'], mix(c['accent'], c['button'], 0.75), c['text'], c['textSecondary'], c, focus)
    g['Header'] = group(c['header'], c['window'], c['text'], c['textSecondary'], c, focus)
    hi = dict(c); 
    gi = group(c['headerInactive'], c['window'], c['text'], c['textSecondary'], c, focus)
    g['Header][Inactive'] = gi
    sel = group(c['accent'], mix(c['accent'], c['view'], 0.55), c['accentText'], mix(c['accentText'], c['accent'], 0.35), c, focus)
    sel['ForegroundLink'] = '#FFE3A6' if c['accentText'] == '#FFFFFF' else '#00304A'; sel['ForegroundActive'] = c['accentText']
    sel['ForegroundNegative'] = '#5A0F0F'; sel['ForegroundNeutral'] = '#5A3A00'; sel['ForegroundPositive'] = '#0F3D24'
    g['Selection'] = sel
    g['Tooltip'] = group(c['tooltip'], mix(c['tooltip'], c['tooltipText'], 0.08), c['tooltipText'], mix(c['tooltipText'], c['tooltip'], 0.35), c, focus)
    g['Tooltip']['ForegroundLink'] = '#8FD0DC' if not dark else '#1C6F86'
    # Complementary: always the deep marine "night" surface (OSD, lock screen, fullscreen chrome)
    d = T['dark']
    comp = group('#10202A', '#0B1922', d['text'], d['textSecondary'], d, focus)
    comp['ForegroundLink'] = d['link']
    g['Complementary'] = comp

    name = name or ('VelaDark' if dark else 'VelaLight')
    label = label or (('Vela scuro', 'Vela Dark') if dark else ('Vela chiaro', 'Vela Light'))
    lines = ['# Vela color scheme — generated by components/theme/src/gen_colors.py from tokens.json', '# SPDX-License-Identifier: LGPL-2.0-or-later', '']
    lines += ['[ColorEffects:Disabled]', 'Color=%s' % ('56,56,56' if not dark else '112,111,110'), 'ColorAmount=0', 'ColorEffect=0',
              'ContrastAmount=%s' % ('0.65' if not dark else '0.65'), 'ContrastEffect=1', 'IntensityAmount=0.1', 'IntensityEffect=2', '']
    lines += ['[ColorEffects:Inactive]', 'ChangeSelectionColor=true', 'Color=112,111,110', 'ColorAmount=0.025', 'ColorEffect=2',
              'ContrastAmount=0.1', 'ContrastEffect=2', 'Enable=false', 'IntensityAmount=0', 'IntensityEffect=0', '']
    for k in ['Button', 'Complementary', 'Header', 'Header][Inactive', 'Selection', 'Tooltip', 'View', 'Window']:
        lines.append('[Colors:%s]' % k)
        for kk in sorted(g[k]):
            lines.append('%s=%s' % (kk, rgb(g[k][kk])))
        lines.append('')
    lines += ['[General]', 'ColorScheme=%s' % name, 'Name=%s' % label[1], 'Name[it]=%s' % label[0],
              'shadeSortColumn=true', '', '[KDE]', 'contrast=4', '']
    lines += ['[WM]', 'activeBackground=%s' % rgb(c['header']), 'activeBlend=%s' % rgb(c['header']),
              'activeForeground=%s' % rgb(c['text']), 'inactiveBackground=%s' % rgb(c['headerInactive']),
              'inactiveBlend=%s' % rgb(c['headerInactive']), 'inactiveForeground=%s' % rgb(c['textSecondary']), '']
    os.makedirs(OUT, exist_ok=True)
    open(os.path.join(OUT, name + '.colors'), 'w').write('\n'.join(lines))
    print('wrote', name)

scheme('light'); scheme('dark')
HC_LIGHT = dict(window='#FFFFFF', view='#FFFFFF', viewAlt='#F2F2F2', header='#FFFFFF', headerInactive='#FFFFFF', button='#FFFFFF',
                text='#000000', textSecondary='#2B2B2B', accent='#A8381F', accentText='#FFFFFF', link='#00507A',
                tooltip='#000000', tooltipText='#FFFFFF', positive='#0B6B35', neutral='#7A4A00', negative='#A30000')
HC_DARK = dict(window='#000000', view='#000000', viewAlt='#141414', header='#000000', headerInactive='#000000', button='#1A1A1A',
               text='#FFFFFF', textSecondary='#E0E0E0', accent='#FFB4A1', accentText='#000000', link='#8FE3FF',
               tooltip='#FFFFFF', tooltipText='#000000', positive='#7CF0A8', neutral='#FFD27A', negative='#FF9C9C')
scheme('light', HC_LIGHT, 'VelaHighContrast', ('Vela contrasto elevato', 'Vela High Contrast'))
scheme('dark', HC_DARK, 'VelaHighContrastDark', ('Vela contrasto elevato scuro', 'Vela High Contrast Dark'))
